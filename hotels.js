// ============================================================

function showFinalTripSummary() {

    const section =
        document.getElementById("finalTripSummary");

    if (!section) return;


    // -----------------------------
    // TRAVEL AMOUNT
    // -----------------------------

    const travelAmount =
        Number(
            localStorage.getItem("travelBookingAmount")
        ) || 0;


    // -----------------------------
    // HOTEL AMOUNT
    // -----------------------------

    const hotelBooking =
        getFinalJSON("lastHotelBooking");

    let hotelAmount =
        Number(
            localStorage.getItem("hotelTotalAmount")
        ) || 0;


    // Use latest hotel booking amount
    if (
        hotelBooking &&
        Number(hotelBooking.totalAmount) > 0
    ) {
        hotelAmount =
            Number(hotelBooking.totalAmount);
    }


    // -----------------------------
    // DARSHAN AMOUNT
    // -----------------------------

    let darshanAmount =
        Number(
            localStorage.getItem("darshanBookingAmount")
        ) || 0;


    const darshanBookings =
        getFinalJSON("travelDarshanBookings");


    if (
        Array.isArray(darshanBookings) &&
        darshanBookings.length > 0
    ) {

        const latestDarshan =
            darshanBookings[0];

        const darshanPrice =
            Number(
                latestDarshan.totalPrice ||
                latestDarshan.price ||
                latestDarshan.amount ||
                0
            );

        if (darshanPrice > 0) {
            darshanAmount = darshanPrice;
        }
    }


    // -----------------------------
    // TOTAL
    // -----------------------------

    const total =
        travelAmount +
        hotelAmount +
        darshanAmount;


    // -----------------------------
    // DISPLAY AMOUNTS
    // -----------------------------

    const travelBox =
        document.getElementById(
            "finalTravelAmount"
        );

    const hotelBox =
        document.getElementById(
            "finalHotelAmount"
        );

    const darshanBox =
        document.getElementById(
            "finalDarshanAmount"
        );

    const totalBox =
        document.getElementById(
            "finalTripTotal"
        );

    const payBox =
        document.getElementById(
            "finalPayAmount"
        );


    if (travelBox)
        travelBox.textContent =
            formatFinalMoney(travelAmount);


    if (hotelBox)
        hotelBox.textContent =
            formatFinalMoney(hotelAmount);


    if (darshanBox)
        darshanBox.textContent =
            formatFinalMoney(darshanAmount);


    if (totalBox)
        totalBox.textContent =
            formatFinalMoney(total);


    if (payBox)
        payBox.textContent =
            formatFinalMoney(total);


    // -----------------------------
    // SHOW SUMMARY
    // -----------------------------

    section.style.display = "block";


    section.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });
}


