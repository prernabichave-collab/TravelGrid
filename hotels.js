// CONFIRM HOTEL BOOKING
// ===============================
function confirmHotelBooking(event) {

    if (event) {
        event.preventDefault();
    }

    if (!selectedHotel) {
        alert("Please select a hotel first.");
        return;
    }

    const guestName =
        document.getElementById("guestName")?.value.trim();

    const mobile =
        document.getElementById("guestMobile")?.value.trim();

    const checkIn =
        document.getElementById("checkIn")?.value;

    const checkOut =
        document.getElementById("checkOut")?.value;

    const guests =
        Number(
            document.getElementById("guestCount")?.value || 1
        );

    const rooms =
        Number(
            document.getElementById("roomCount")?.value || 1
        );


    if (
        !guestName ||
        !mobile ||
        !checkIn ||
        !checkOut
    ) {
        alert("Please fill all required fields.");
        return;
    }


    if (!/^[6-9]\d{9}$/.test(mobile)) {

        alert(
            "Please enter a valid 10-digit mobile number."
        );

        return;
    }


    if (
        new Date(checkOut) <=
        new Date(checkIn)
    ) {

        alert(
            "Check-out date must be after check-in date."
        );

        return;
    }


    const oneDay =
        24 * 60 * 60 * 1000;

    const nights =
        Math.ceil(
            (
                new Date(checkOut) -
                new Date(checkIn)
            ) / oneDay
        );

    const roomPrice =
        Number(
            selectedHotel.pricePerNight || 0
        );



    const totalAmount =
        roomPrice *
        rooms *
        nights;



    const booking = {

        bookingId:
            "TG-HOTEL-" + Date.now(),

        hotelName:
            selectedHotel.hotelName || "",

        city:
            selectedHotel.city || "",

        place:
            selectedHotel.place || "",

        area:
            selectedHotel.area || "",

        address:
            selectedHotel.address || "",

        guestName:
            guestName,

        mobile:
            mobile,

        checkIn:
            checkIn,

        checkOut:
            checkOut,

        guests:
            guests,

        rooms:
            rooms,

        nights:
            nights,

        pricePerNight:
            roomPrice,

        totalAmount:
            totalAmount,

        status:
            "Confirmed",

        bookingDate:
            new Date().toISOString()
    };



    let hotelBookings =
        JSON.parse(
            localStorage.getItem("hotelBookings")
        ) || [];


    hotelBookings.push(booking);


    localStorage.setItem(
        "hotelBookings",
        JSON.stringify(hotelBookings)
    );


    localStorage.setItem(
        "lastHotelBooking",
        JSON.stringify(booking)
    );
    showFinalTripSummary();

    localStorage.setItem(
        "hotelTotalAmount",
        String(totalAmount)
    );

    // ==================================================
    // FINAL TRIP TOTAL
    // ==================================================

    const travelAmount =
        Number(localStorage.getItem("travelBookingAmount")) || 0;

    const hotelAmount =
        Number(totalAmount) || 0;

    const darshanAmount =
        Number(localStorage.getItem("darshanBookingAmount")) || 0;

    const finalTotal =
        travelAmount +
        hotelAmount +
        darshanAmount;

    localStorage.setItem(
        "travelGridTotalAmount",
        String(finalTotal)
    );

    localStorage.setItem(
        "travelGuestName",
        guestName
    );

    localStorage.setItem(
        "travelMobile",
        mobile
    );

    closeBookingForm();



    showHotelBookingConfirmation(booking);
}

