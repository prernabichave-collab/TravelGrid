// ============================================================
// COMPLETE FINAL PAYMENT
// ============================================================

function completeFinalPayment() {

    if (!selectedFinalPayment) {

        alert(
            "Please select a payment method first."
        );

        return;
    }


    // ========================================================
    // GET AMOUNTS
    // ========================================================

    const travelAmount =
        Number(
            localStorage.getItem(
                "travelBookingAmount"
            )
        ) || 0;


    let hotelAmount =
        Number(
            localStorage.getItem(
                "hotelTotalAmount"
            )
        ) || 0;


    const hotelBooking =
        getFinalJSON("lastHotelBooking");


    if (
        hotelBooking &&
        Number(hotelBooking.totalAmount) > 0
    ) {
        hotelAmount =
            Number(hotelBooking.totalAmount);
    }


    const darshanAmount =
        Number(
            localStorage.getItem(
                "darshanBookingAmount"
            )
        ) || 0;


    const totalAmount =
        travelAmount +
        hotelAmount +
        darshanAmount;


    if (totalAmount <= 0) {

        alert(
            "No booking amount found."
        );

        return;
    }


    // ========================================================
    // PAYMENT VALIDATION
    // ========================================================

    if (selectedFinalPayment === "UPI") {

        const upi =
            document
                .getElementById("finalUpiId")
                ?.value
                .trim();


        if (
            !upi ||
            !upi.includes("@")
        ) {

            alert(
                "Please enter a valid demo UPI ID."
            );

            return;
        }
    }


    if (selectedFinalPayment === "Card") {

        const card =
            document
                .getElementById("finalCardNumber")
                ?.value
                .replace(/\s/g, "");


        const expiry =
            document
                .getElementById("finalCardExpiry")
                ?.value
                .trim();


        const cvv =
            document
                .getElementById("finalCardCVV")
                ?.value
                .trim();


        if (
            !card ||
            card.length < 12 ||
            !expiry ||
            !cvv ||
            cvv.length < 3
        ) {

            alert(
                "Please enter valid demo card details."
            );

            return;
        }
    }


    if (selectedFinalPayment === "Online") {

        const bank =
            document
                .getElementById("finalBank")
                ?.value;


        const customerId =
            document
                .getElementById("finalCustomerId")
                ?.value
                .trim();


        if (!bank || !customerId) {

            alert(
                "Please enter demo online banking details."
            );

            return;
        }
    }


    // ========================================================
    // GET GUEST DETAILS
    // ========================================================

    const travelGuestName =
        localStorage.getItem(
            "travelGuestName"
        ) || "";


    const travelMobile =
        localStorage.getItem(
            "travelMobile"
        ) || "";


    const bookingId =
        "TG-" +
        Date.now();


    // ========================================================
    // FINAL BOOKING OBJECT
    // ========================================================

    const finalBooking = {

        bookingId:

            bookingId,

        guestName:

            travelGuestName,

        mobile:

            travelMobile,

        travelAmount:

            travelAmount,

        hotelAmount:

            hotelAmount,

        darshanAmount:

            darshanAmount,

        totalAmount:

            totalAmount,

        paymentMethod:

            selectedFinalPayment,

        status:

            selectedFinalPayment === "Cash"
                ? "PAY AT COUNTER"
                : "PAID / CONFIRMED",

        bookingDate:

            new Date().toLocaleString(
                "en-IN"
            )

    };


    // ========================================================
    // SAVE FINAL BOOKING
    // ========================================================

    localStorage.setItem(
        "travelGridFinalBooking",
        JSON.stringify(finalBooking)
    );


    localStorage.setItem(
        "travelGridTotalAmount",
        String(totalAmount)
    );


    // ========================================================
    // SHOW FINAL BILL
    // ========================================================

    showFinalBill(finalBooking);
}


